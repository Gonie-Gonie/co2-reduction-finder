"""Measure an installed Windows Python inference runtime without counting unrelated packages.

This is an installed-file estimate, not an installer/download size or a proof that
all files are needed at run time. Distribution RECORD entries include native DLLs,
``.libs`` directories, metadata, and entry-point scripts outside site-packages.
The full standard library is included; generated bytecode is excluded everywhere.
No packages are imported or installed by this script other than ``packaging``.
"""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import json
import os
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


ROOT = Path(__file__).resolve().parents[1]
ROOT_PACKAGES = ("tensorflow", "keras", "h5py", "numpy")


def generated_bytecode(path: Path) -> bool:
    return path.suffix.lower() in {".pyc", ".pyo"} or "__pycache__" in path.parts


def total_bytes(paths: set[Path]) -> int:
    return sum(path.stat().st_size for path in paths)


def collect_distributions() -> tuple[dict, set[Path]]:
    """Resolve installed Requires-Dist with current-platform markers, no extras.

    Versions are checked even when a dependency was already visited. CUDA and
    other optional extras are deliberately excluded by evaluating extra=''.
    Missing required distributions and incompatible versions abort the report.
    """
    environment = {**default_environment(), "extra": ""}
    pending = [Requirement(name) for name in ROOT_PACKAGES]
    distributions = {}
    included_files: set[Path] = set()
    while pending:
        requirement = pending.pop()
        if requirement.marker and not requirement.marker.evaluate(environment):
            continue
        name = canonicalize_name(requirement.name)
        try:
            distribution = metadata.distribution(name)
        except metadata.PackageNotFoundError as error:
            raise RuntimeError(f"Required installed package is missing: {requirement}") from error
        if not requirement.specifier.contains(distribution.version, prereleases=True):
            raise RuntimeError(
                f"Installed {name}=={distribution.version} does not satisfy {requirement}"
            )
        if name in distributions:
            continue
        if distribution.files is None:
            raise RuntimeError(f"{name} has no installed-file metadata (RECORD)")

        package_files: set[Path] = set()
        excluded_bytecode_files = 0
        excluded_bytecode_bytes = 0
        missing_record_entries = []
        for entry in distribution.files:
            path = Path(distribution.locate_file(entry)).resolve()
            if generated_bytecode(path):
                excluded_bytecode_files += 1
                if path.is_file():
                    excluded_bytecode_bytes += path.stat().st_size
                continue
            if path.is_file():
                package_files.add(path)
            else:
                missing_record_entries.append(str(entry))

        active_requirements = []
        for text in distribution.requires or []:
            dependency = Requirement(text)
            if not dependency.marker or dependency.marker.evaluate(environment):
                active_requirements.append(str(dependency))
                pending.append(dependency)
        distributions[name] = {
            "version": distribution.version,
            "file_count": len(package_files),
            "bytes": total_bytes(package_files),
            "excluded_bytecode_file_count": excluded_bytecode_files,
            "excluded_bytecode_bytes": excluded_bytecode_bytes,
            "missing_record_entries": sorted(missing_record_entries),
            "active_requirements": sorted(active_requirements),
        }
        included_files.update(package_files)

    return {
        "roots": list(ROOT_PACKAGES),
        "extra": "",
        "distribution_count": len(distributions),
        "file_count": len(included_files),
        "bytes": total_bytes(included_files),
        "distributions": dict(sorted(distributions.items())),
    }, included_files


def collect_base_runtime() -> tuple[dict, set[Path]]:
    """Count Windows interpreter, native runtime, DLLs, and the full stdlib.

    Lib includes tests, idlelib, tkinter, ensurepip, etc.; this intentionally
    avoids claiming an aggressively trimmed deployment. Lib/site-packages and
    generated bytecode are excluded. Dependency files are counted separately.
    """
    if sys.platform != "win32":
        raise RuntimeError("This base-interpreter inventory currently supports Windows only")
    base = Path(sys.base_prefix).resolve()
    candidates: set[Path] = set()
    for pattern in ("python*.exe", "python*.dll", "python*.zip", "vcruntime*.dll"):
        candidates.update(path.resolve() for path in base.glob(pattern) if path.is_file())
    for directory in (base / "DLLs", base / "Lib"):
        if not directory.is_dir():
            raise RuntimeError(f"Expected interpreter directory is missing: {directory}")
        for current, directories, filenames in os.walk(directory):
            # Do not even inventory unrelated packages: a large general-purpose
            # environment must not affect this count or its traversal cost.
            directories[:] = [name for name in directories if name != "site-packages"]
            candidates.update((Path(current) / name).resolve() for name in filenames)

    included: set[Path] = set()
    excluded_bytecode_count = 0
    excluded_bytecode_bytes = 0
    for path in candidates:
        if generated_bytecode(path):
            excluded_bytecode_count += 1
            excluded_bytecode_bytes += path.stat().st_size
        else:
            included.add(path)
    return {
        "base_prefix": str(base),
        "file_count": len(included),
        "bytes": total_bytes(included),
        "included": [
            "base-prefix python*.exe, python*.dll, python*.zip, vcruntime*.dll",
            "DLLs/**",
            "Lib/** (including stdlib tests and optional stdlib modules)",
        ],
        "excluded": ["Lib/site-packages/**", "**/__pycache__/**", "*.pyc", "*.pyo"],
        "excluded_bytecode_file_count": excluded_bytecode_count,
        "excluded_bytecode_bytes": excluded_bytecode_bytes,
    }, included


def artifact(path: Path) -> dict:
    return {
        "path": str(path.relative_to(ROOT)),
        "exists": path.is_file(),
        "bytes": path.stat().st_size if path.is_file() else None,
    }


def measure(rust_target: str | None = None) -> dict:
    packages, package_files = collect_distributions()
    base, base_files = collect_base_runtime()
    runtime_files = base_files | package_files
    models = {path.resolve() for path in (ROOT / "models").rglob("*.h5") if path.is_file()}
    if not models:
        raise RuntimeError("No source .h5 models found under models/")
    benchmark_script = ROOT / "scripts" / "benchmark_models.py"
    support_files = {
        benchmark_script.resolve(),
        (ROOT / "models" / "ann" / "v1" / "model_registry.json").resolve(),
    }
    if not all(path.is_file() for path in support_files):
        raise RuntimeError("Python benchmark script or model registry is missing")
    release_directory = ROOT / "target"
    if rust_target:
        release_directory = release_directory / rust_target
    release_directory = release_directory / "release"
    return {
        "measured_at_utc": datetime.now(timezone.utc).isoformat(),
        "python": {
            "version": platform.python_version(),
            "executable": sys.executable,
            "platform": platform.platform(),
            "architecture": platform.machine(),
        },
        "methodology": [
            "Installed uncompressed file sizes, not installer, archive, or RAM sizes.",
            "TensorFlow/Keras/h5py/NumPy installed Requires-Dist transitive closure; current environment markers; extra=''.",
            "Each real RECORD file counted once by resolved absolute path, including dist-info, native libraries, and external entry-point scripts.",
            "Generated .pyc/.pyo and __pycache__ files excluded; absent RECORD paths are reported, not counted.",
            "Base Python includes the full standard library except site-packages and generated bytecode; unrelated installed distributions are excluded.",
            "No pip, development headers, Python import libraries, documentation, or installers are added unless present inside a selected distribution or the included stdlib.",
            "Shared system DLLs outside the Python installation and operating system are excluded on both sides.",
            "Rust executable sizes include embedded assets; do not add assets/models.c2m again to either executable.",
        ],
        "python_dependencies": packages,
        "base_python_runtime": base,
        "python_runtime": {"file_count": len(runtime_files), "bytes": total_bytes(runtime_files)},
        "source_h5": {
            "count": len(models),
            "bytes": total_bytes(models),
            "files": [artifact(path) for path in sorted(models)],
        },
        "python_runtime_plus_all_h5": {
            "file_count": len(runtime_files | models),
            "bytes": total_bytes(runtime_files | models),
        },
        "python_benchmark_script": artifact(benchmark_script),
        "python_inference_support_files": [artifact(path) for path in sorted(support_files)],
        "python_runtime_plus_all_h5_and_support_files": {
            "file_count": len(runtime_files | models | support_files),
            "bytes": total_bytes(runtime_files | models | support_files),
        },
        "rust_artifacts": {
            "target": rust_target,
            "converted_model_binary": artifact(ROOT / "assets" / "models.c2m"),
            "application_exe": artifact(release_directory / "co2-reduction-finder.exe"),
            "benchmark_exe": artifact(release_directory / "examples" / "model_benchmark.exe"),
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Also write the JSON report to this path")
    parser.add_argument("--rust-target", help="Cargo target triple, e.g. x86_64-pc-windows-gnu")
    args = parser.parse_args()
    report = json.dumps(measure(args.rust_target), ensure_ascii=False, indent=2)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report + "\n", encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
